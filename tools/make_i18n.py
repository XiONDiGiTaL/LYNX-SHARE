# Embeds the translation tables in the executable.
# Usage: python3 tools/make_i18n.py   (from the repository root)
# Reads every resources/i18n/<id>.txt and writes src/ui/i18n/<id>.h (the table zlib-compressed: the plain
# tables are ~490 KB each, compressed ~169 KB; one header per language so a fix to one table changes one file)
# plus src/ui/I18nData.h (the list). Unpacked with lynx::inflateZlib when a language is chosen.
#
# The compression is tools/deflate_det.py, not zlib.compress(): only the input decides the bytes it emits, so the
# headers come out identical on every machine. zlib's own stream varies with the zlib build linked into Python
# (1.2.x and 1.3 pick different matches at level 9), which made every header differ after a regeneration on another
# machine even though the text was the same.
#
# The tables are independent, so they are packed one process per core (the compressor is pure Python, and CPU-bound);
# the headers written are the same whatever the worker count or completion order.
import concurrent.futures, os, pathlib, sys, zlib

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import deflate_det  # noqa: E402

root = pathlib.Path(__file__).resolve().parent.parent
folder = root / "src/ui/i18n"


def pack(lang):
    """One table's embedded bytes: CRLF folded to LF (a Windows checkout has CRLF, CI has LF, and the headers must
    match), then compressed."""
    data = (root / f"resources/i18n/{lang}.txt").read_bytes().replace(b"\r\n", b"\n")
    packed = deflate_det.compress(data)
    if zlib.decompress(packed) != data: # zlib only reads here: the bytes written are deflate_det's
        raise RuntimeError(f"deflate_det.compress produced a stream that does not decode {lang}.txt")
    return lang, data, packed


def tableHeader(lang, data, packed):
    name = "t_" + lang.replace("-", "_")
    part = ["#pragma once", "",
            f"// Generated by tools/make_i18n.py from resources/i18n/{lang}.txt ({len(data)} bytes, zlib) - do not edit by hand.",
            "", "namespace lynx::i18n::data", "{",
            f"inline constexpr unsigned char {name}[] = {{"]
    for i in range(0, len(packed), 32):
        part.append(",".join(str(b) for b in packed[i:i + 32]) + ",")
    part += ["};", "} // namespace lynx::i18n::data", ""]
    return name, "\n".join(part)


def main():
    # fixed order: the order of the Language menu is set in src/ui/I18n.cpp, this one only names the arrays
    ids = sorted(p.stem for p in (root / "resources/i18n").glob("*.txt"))

    folder.mkdir(exist_ok=True)
    for stale in folder.glob("*.h"):
        if stale.stem not in ids:
            stale.unlink()

    jobs = min(len(ids), os.cpu_count() or 1)
    if jobs > 1:
        with concurrent.futures.ProcessPoolExecutor(max_workers=jobs) as pool:
            tables = list(pool.map(pack, ids))
    else:
        tables = [pack(lang) for lang in ids]

    out = ["#pragma once", "",
           "// Generated by tools/make_i18n.py from resources/i18n/*.txt - do not edit by hand.", "",
           "#include <cstddef>", "",
           "namespace lynx::i18n::data", "{",
           "struct Table",
           "{",
           "    const char* id;                 // \"pt-BR\"",
           "    const unsigned char* zlib;      // the .txt file, zlib-compressed",
           "    std::size_t zlibSize, textSize; // compressed / original size in bytes",
           "};", "} // namespace lynx::i18n::data", ""]
    names = []
    for lang, data, packed in tables:
        name, text = tableHeader(lang, data, packed)
        names.append((lang, name, len(packed), len(data)))
        (folder / f"{lang}.h").write_text(text, encoding="utf-8", newline="\n")
        out.append(f'#include "ui/i18n/{lang}.h"')

    out += ["", "namespace lynx::i18n::data", "{", "inline constexpr Table tables[] = {"]
    for lang, name, n, size in names:
        out.append(f'    {{ "{lang}", {name}, {n}, {size} }},')
    out.append("};")
    out.append("} // namespace lynx::i18n::data")
    out.append("")
    (root / "src/ui/I18nData.h").write_text("\n".join(out), encoding="utf-8", newline="\n")
    print(f"{len(names)} table(s) -> src/ui/i18n/*.h + src/ui/I18nData.h")


if __name__ == "__main__":
    main()
